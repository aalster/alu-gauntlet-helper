def set_ui_language(language: str) -> None:
    global _language
    _language = UK if language == UK else EN


def current_ui_language() -> str:
    return _language


def t(key: str) -> str:
    """Рядок поточної мови; фолбек: поточна → en → сам ключ."""
    current = TRANSLATIONS.get(_language, {})
    if key in current:
        return current[key]
    return TRANSLATIONS["en"].get(key, key)


def runs_word(n: int) -> str:
    """Слово «заїзд» у формі множини для n: 1 заїзд / 2 заїзди / 5 заїздів; run / runs."""
    if _language == UK:
        # відкладений імпорт: utils так само ліниво імпортує ui_lang (format_relative_time)
        from alu_gauntlet_helper.utils.utils import _uk_plural
        return _uk_plural(n, "заїзд", "заїзди", "заїздів")
    return "run" if n == 1 else "runs"


def system_to_ui_language(locale_name: str) -> str:
    """OS-локаль (напр. 'uk_UA') → мова UI. uk/ru → uk, інакше en."""
    code = (locale_name or "").lower()[:2]
    return UK if code in ("uk", "ru") else EN
